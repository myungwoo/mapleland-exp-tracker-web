/**
 * 레벨(LEVEL) 숫자 스프라이트 글리프 템플릿
 *
 * 배경
 * - 레벨 숫자는 오렌지 타일 위에 얹힌 흰 숫자입니다. EXP 글꼴과 마찬가지로 안티에일리어싱이
 *   전혀 없는 픽셀 글꼴이라, 픽셀 단위 템플릿 매칭으로 사실상 100% 정확하게 읽을 수 있습니다.
 * - 글꼴 원본은 **7px 높이**이고, 게임은 이걸 **2배로 렌더**합니다. 그래서 100% 배율 캡처에서는
 *   글리프가 14px 높이로 보입니다. (EXP 숫자가 7px인 것에 비해 두 배 크고, 그만큼 더 안정적입니다)
 * - 획 두께가 2px인 "볼드" 계열이라 EXP 글꼴(획 1px, 숫자 폭 5px)과는 **다른 글꼴**입니다.
 *
 * ⚠️ EXP 글꼴에서 유도하지 마세요 (실제로 시도해서 틀렸습니다)
 *   두 글꼴은 골격이 거의 같아서 "EXP 글리프를 볼드 처리하면 되겠다"는 생각이 자연스럽게 듭니다.
 *   하지만 `1` 만 우연히 맞고 나머지는 폭이 1px씩 다릅니다.
 *     "1": EXP 볼드 폭 3 vs 레벨 폭 3 → 일치
 *     "9": EXP 볼드 폭 6 vs 레벨 폭 7 → 불일치
 *     "3": EXP 볼드 폭 6 vs 레벨 폭 7 → 불일치
 *   유도한 템플릿은 일관되게 1px 좁아지는데, 크기 허용오차가 이를 통과시켜 **조용히 오인식**합니다.
 *   글꼴이 바뀌면 반드시 실제 캡처에서 다시 뽑으세요. (`tools/level-font/extract-templates.mjs`)
 *
 * 출처
 * - 전부 실제 게임 캡처에서 픽셀 단위로 추출했습니다.
 * - 서로 다른 캡처에 같은 숫자가 겹쳐 나온 경우(`1`, `3`, `6`)는 전부 **완전히 동일**한 것을
 *   확인했습니다. 즉 글리프는 화면 위치나 캡처 시점과 무관한 고정 패턴입니다.
 *
 * 좌표계
 * - 모든 숫자가 높이 7, 윗줄이 같습니다. (EXP 글꼴처럼 글리프별 세로 오프셋이 없습니다)
 * - 가로는 "잉크(전경 픽셀)의 타이트한 bbox"만 담습니다. `1` 만 폭 3이고 나머지는 전부 폭 7입니다.
 */

export type LevelGlyph = {
	char: string;
	width: number;
	height: number;
	/** '#' = 전경(글자), '.' = 배경 */
	rows: string[];
};

/** 레벨 글꼴 원본 높이(px). 관측된 글리프 높이를 이 값으로 나눠 캡처 배율을 추정합니다. */
export const LEVEL_FONT_DIGIT_HEIGHT = 7;

function glyph(char: string, rows: string[]): LevelGlyph {
	return { char, width: rows.reduce((m, r) => Math.max(m, r.length), 0), height: rows.length, rows };
}

export const LEVEL_FONT_GLYPHS: LevelGlyph[] = [
	glyph("0", [".#####.", "##...##", "##...##", "##...##", "##...##", "##...##", ".#####."]),
	glyph("1", [".##", "###", ".##", ".##", ".##", ".##", ".##"]),
	glyph("2", [".#####.", "##...##", ".....##", "..####.", ".##....", "##.....", "#######"]),
	glyph("3", [".#####.", "##...##", ".....##", "..####.", ".....##", "##...##", ".#####."]),
	glyph("4", ["...###.", "..####.", ".##.##.", "##..##.", "#######", "....##.", "....##."]),
	glyph("5", ["#######", "##.....", "##.....", ".#####.", ".....##", "##...##", ".#####."]),
	glyph("6", [".#####.", "##...##", "##.....", "######.", "##...##", "##...##", ".#####."]),
	glyph("7", ["#######", ".....##", "....##.", "...##..", "...##..", "..##...", "..##..."]),
	glyph("8", [".#####.", "##...##", "##...##", ".#####.", "##...##", "##...##", ".#####."]),
	glyph("9", [".#####.", "##...##", "##...##", ".######", ".....##", "##...##", ".#####."])
];

/** 템플릿을 0/1 배열로 미리 펼쳐둡니다. (매칭 루프에서 문자열 인덱싱 비용 제거) */
export type LevelGlyphMask = LevelGlyph & { bits: Uint8Array };

export const LEVEL_FONT_MASKS: LevelGlyphMask[] = LEVEL_FONT_GLYPHS.map((g) => {
	const bits = new Uint8Array(g.width * g.height);
	for (let y = 0; y < g.height; y++) {
		const row = g.rows[y];
		for (let x = 0; x < g.width; x++) {
			bits[y * g.width + x] = row[x] === "#" ? 1 : 0;
		}
	}
	return { ...g, bits };
});
