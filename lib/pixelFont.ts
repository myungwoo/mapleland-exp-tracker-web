/**
 * 메이플랜드 2.0 "비트맵(픽셀) 글꼴" 글리프 템플릿
 *
 * 배경
 * - 2.0 패치로 EXP 텍스트가 구 메이플스토리 고증에 맞춰 **비트맵 글꼴**로 바뀌었습니다.
 * - 이 글꼴은 안티에일리어싱이 전혀 없는 픽셀 폰트이고, 숫자는 5x7px 고정 크기입니다.
 *
 * 실제 캡처에서 측정한 지표 (원본 배율 기준)
 * - 숫자: 잉크 5x7px, advance 6px (고정폭). `1`만 잉크 2px
 * - `[` `]`: 2x9px, advance 4px  /  `.`: 1x2px  /  `%`: 7x7px
 * - 색: 숫자/`%`는 흰색(#FFFFFF), 대괄호는 연두색(#99CC33), 배경은 어두운 UI 바
 * - 디자인은 Arial/Helvetica 계열이지만, 어떤 시스템 폰트를 래스터라이즈해도 그대로 나오지는 않습니다.
 *   (설치된 폰트 전수 대조 결과 Arial 10px가 12자 중 8자 일치로 최고. Windows 돋움/굴림 11px 비트맵은
 *    숫자가 8px 높이라 아예 다름) 즉 손으로 다듬은 비트맵 글꼴이며, 그래서 **템플릿은 반드시 실제
 *   게임 캡처에서 뽑아야 합니다.** 비슷한 폰트에서 유추하면 5, 7처럼 틀립니다. (실제로 틀렸습니다)
 * - 글리프가 고정된 픽셀 패턴이라, 픽셀 단위로 맞춰보면 사실상 100% 정확하게 읽을 수 있습니다.
 *
 * 좌표계
 * - `top`은 **숫자 글리프의 첫 행(=0)** 을 기준으로 한 세로 오프셋입니다.
 *   - 숫자: top = 0, 높이 7
 *   - `[` `]`: top = -1, 높이 9 (숫자보다 한 줄 위에서 시작해 한 줄 아래까지)
 *   - `.`   : top = 6, 높이 2 (베이스라인 행 + 그 아래 한 행)
 * - 가로는 "잉크(전경 픽셀)의 타이트한 bbox"만 담습니다. (advance/사이드베어링은 사용하지 않습니다)
 *
 * 템플릿 출처
 * - 전부 실제 게임 캡처에서 픽셀 단위로 추출했습니다. (`]` 만 `[` 의 좌우 대칭으로 확정)
 * - 패치로 글꼴이 바뀌거나 새 글자가 필요하면 `tools/pixel-font/extract-templates.mjs` 로 다시 뽑으세요.
 */

export type PixelGlyph = {
	char: string;
	/** 숫자 글리프 첫 행을 0으로 했을 때의 세로 오프셋 */
	top: number;
	width: number;
	height: number;
	/** '#' = 전경(글자), '.' = 배경 */
	rows: string[];
};

/** 숫자 글리프의 높이(px). 스케일 추정의 기준이 됩니다. */
export const PIXEL_FONT_DIGIT_HEIGHT = 7;

function glyph(char: string, top: number, rows: string[]): PixelGlyph {
	return {
		char,
		top,
		width: rows.reduce((m, r) => Math.max(m, r.length), 0),
		height: rows.length,
		rows
	};
}

export const PIXEL_FONT_GLYPHS: PixelGlyph[] = [
	glyph("0", 0, [".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."]),
	glyph("1", 0, [".#", "##", ".#", ".#", ".#", ".#", ".#"]),
	glyph("2", 0, [".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####"]),
	glyph("3", 0, [".###.", "#...#", "....#", "..##.", "....#", "#...#", ".###."]),
	glyph("4", 0, ["...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#."]),
	glyph("5", 0, ["#####", "#....", "#....", ".###.", "....#", "#...#", ".###."]),
	glyph("6", 0, [".###.", "#...#", "#....", "####.", "#...#", "#...#", ".###."]),
	glyph("7", 0, ["#####", "....#", "....#", "....#", "...#.", "..#..", "..#.."]),
	glyph("8", 0, [".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###."]),
	glyph("9", 0, [".###.", "#...#", "#...#", ".####", "....#", "#...#", ".###."]),
	glyph("%", 0, [".#....#", "#.#..#.", ".#..#..", "...#...", "..#..#.", ".#..#.#", "#....#."]),
	glyph("[", -1, ["##", "#.", "#.", "#.", "#.", "#.", "#.", "#.", "##"]),
	// `]` 는 `[` 의 좌우 대칭이라 캡처 없이도 안전하게 확정할 수 있습니다.
	glyph("]", -1, ["##", ".#", ".#", ".#", ".#", ".#", ".#", ".#", "##"]),
	glyph(".", 6, ["#", "#"])
];

/** 템플릿을 0/1 배열로 미리 펼쳐둡니다. (매칭 루프에서 문자열 인덱싱 비용 제거) */
export type PixelGlyphMask = PixelGlyph & { bits: Uint8Array };

export const PIXEL_FONT_MASKS: PixelGlyphMask[] = PIXEL_FONT_GLYPHS.map((g) => {
	const bits = new Uint8Array(g.width * g.height);
	for (let y = 0; y < g.height; y++) {
		const row = g.rows[y];
		for (let x = 0; x < g.width; x++) {
			bits[y * g.width + x] = row[x] === "#" ? 1 : 0;
		}
	}
	return { ...g, bits };
});
